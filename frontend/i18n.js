let currentLang = localStorage.getItem("kefu-lang") || "zh";

function t(key) {
  const pack = I18N[currentLang] || I18N.zh;
  if (Object.prototype.hasOwnProperty.call(pack, key)) return pack[key];
  if (Object.prototype.hasOwnProperty.call(I18N.zh, key)) return I18N.zh[key];
  return key;
}

function getPrompts() {
  return (I18N[currentLang] || I18N.zh).prompts || I18N.zh.prompts;
}

function getToolLabel(name) {
  const pack = I18N[currentLang] || I18N.zh;
  return (pack.tools && pack.tools[name]) || (I18N.zh.tools && I18N.zh.tools[name]) || name;
}

function setText(selectorOrEl, value) {
  const el =
    typeof selectorOrEl === "string"
      ? document.querySelector(selectorOrEl)
      : selectorOrEl;
  if (el) el.textContent = value;
}

function applyLanguage(lang) {
  currentLang = lang;
  localStorage.setItem("kefu-lang", lang);
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.body.classList.toggle("rtl", lang === "ar");
  document.title = t("pageTitle");
  applyFontSettings();
  // data-i18n / data-i18n-placeholder / data-i18n-title
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (key) el.textContent = t(key);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (key) el.placeholder = t(key);
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    const key = el.getAttribute("data-i18n-title");
    if (key) el.title = t(key);
  });

  // Dynamic areas that rebuild content
  if (typeof renderSessionList === "function") renderSessionList();
  if (typeof renderQuickPrompts === "function") renderQuickPrompts();
  if (typeof updateConnStatus === "function") updateConnStatus();
  if (typeof updateAuthUI === "function") updateAuthUI();
  if (typeof persistSessionId === "function") persistSessionId(typeof sessionId !== "undefined" ? sessionId : null);
  if (typeof loadOrders === "function" && typeof currentUser !== "undefined" && currentUser) {
    loadOrders();
  }
  if (typeof refreshHandoffBannerI18n === "function") refreshHandoffBannerI18n();
  if (typeof refreshVisibleChromeI18n === "function") refreshVisibleChromeI18n();

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });
}

function initLanguageSwitcher() {
  // 语言切换已从侧边栏移除，仅保留已保存的语言偏好生效
  applyLanguage(currentLang);
}

function applyFontSettings() {
  try {
    var fam = localStorage.getItem("kefu-font-family") || "system";
    var sizeRaw = localStorage.getItem("kefu-font-size") || "16";
    var css = document.body.style;
    var fontStack = "inherit";
    if (fam === "serif") fontStack = "\"Noto Serif\", \"Times New Roman\", serif";
    else if (fam === "sans") fontStack = "\"Helvetica Neue\", Arial, sans-serif";
    else if (fam === "mono") fontStack = "\"Courier New\", Consolas, monospace";
    css.fontFamily = fontStack;
    var px = 16;
    if (/^\d+$/.test(sizeRaw)) { px = Math.min(28, Math.max(12, Number(sizeRaw))); }
    else if (sizeRaw === "small") px = 14;
    else if (sizeRaw === "large") px = 18;
    else if (sizeRaw === "xlarge") px = 20;
    css.fontSize = px + "px";
  } catch (e) { /* ignore */ }
}

export function getAdminLang() {
  return localStorage.getItem("kefu-lang") || "zh";
}

export function t(key, lang) {
  const pack = ADMIN_I18N[lang] || ADMIN_I18N.zh;
  if (Object.prototype.hasOwnProperty.call(pack, key)) return pack[key];
  return ADMIN_I18N.zh[key] || key;
}

// 应用字体类型 + 大小到整个管理后台界面
export function applyAdminFonts() {
  try {
    const fam = localStorage.getItem("kefu-font-family") || "system";
    const sizeRaw = localStorage.getItem("kefu-font-size") || "16";
    const s = document.body.style;
    if (fam === "serif") s.fontFamily = '"Noto Serif", "Times New Roman", serif';
    else if (fam === "sans") s.fontFamily = '"Helvetica Neue", Arial, sans-serif';
    else if (fam === "mono") s.fontFamily = '"Courier New", Consolas, monospace';
    else s.fontFamily = "";

    let px = 16;
    if (/^\d+$/.test(sizeRaw)) {
      px = Math.min(28, Math.max(12, Number(sizeRaw)));
    } else if (sizeRaw === "small") px = 14;
    else if (sizeRaw === "large") px = 18;
    else if (sizeRaw === "xlarge") px = 20;
    s.fontSize = px + "px";
  } catch (e) { /* ignore */ }
}
